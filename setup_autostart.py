"""
Codex Futura — Windows Autostart Setup
---------------------------------------
Registers the full ecosystem launcher (start_codex_ecosystem.bat) so that
both services start automatically every time Windows logs in:

  * Budget Guardian  — silent background watchdog
  * Codex Monitor    — floating GUI window (layer health + live feed)

Usage
-----
    python setup_autostart.py           # install autostart
    python setup_autostart.py --remove  # uninstall autostart
    python setup_autostart.py --verify  # check installed paths are still valid

How it works
------------
A tiny VBS script is placed in the Windows Startup folder.  On every login
Windows runs the VBS, which calls start_codex_ecosystem.bat invisibly
(window style 0).  The BAT then spawns:

  * pythonw.exe budget_guardian.py  — truly windowless
  * pythonw.exe monitor.py          — Tkinter GUI visible on screen

If you move the project folder or upgrade Python, re-run:
    python setup_autostart.py --remove
    python setup_autostart.py
"""
import os
import re
import sys

STARTUP_FOLDER = os.path.join(
    os.environ["APPDATA"],
    "Microsoft", "Windows", "Start Menu", "Programs", "Startup",
)

HERE     = os.path.dirname(os.path.abspath(__file__))
LAUNCHER = os.path.join(HERE, "start_codex_ecosystem.bat")
VBS_PATH = os.path.join(STARTUP_FOLDER, "codex_futura_ecosystem.vbs")

# Keep legacy name so --remove also cleans up old single-monitor installs
VBS_PATH_LEGACY = os.path.join(STARTUP_FOLDER, "codex_monitor.vbs")


def install() -> None:
    if not os.path.exists(LAUNCHER):
        print(f"✗  Launcher not found at:\n   {LAUNCHER}")
        print("   Make sure start_codex_ecosystem.bat is in the project folder.")
        sys.exit(1)

    # VBS calls the BAT with window style 0 so no console flashes on login.
    # The BAT itself uses `start ""` to spawn children, so the monitor Tkinter
    # window still appears correctly even though the BAT runs hidden.
    vbs = (
        f"' Codex Futura autostart — generated by setup_autostart.py\n"
        f"' Project: {HERE}\n"
        f"' Re-run setup_autostart.py after moving the project folder.\n"
        f"Set WshShell = CreateObject(\"WScript.Shell\")\n"
        f"WshShell.Run \"cmd /c \" & Chr(34) & \"{LAUNCHER}\" & Chr(34), 0\n"
        f"Set WshShell = Nothing\n"
    )

    os.makedirs(STARTUP_FOLDER, exist_ok=True)
    with open(VBS_PATH, "w") as f:
        f.write(vbs)

    # Remove legacy single-monitor entry if present
    if os.path.exists(VBS_PATH_LEGACY):
        os.remove(VBS_PATH_LEGACY)
        print("   (removed old codex_monitor.vbs — replaced by ecosystem launcher)")

    print("✓  Autostart installed.")
    print(f"   Script  : {VBS_PATH}")
    print(f"   Runs    : {LAUNCHER}")
    print()
    print("   On every Windows login, two services will start automatically:")
    print("     * Budget Guardian  — silent background watchdog")
    print("     * Codex Monitor    — floating GUI window, top-right of screen")
    print()
    print("   To test right now (without restarting Windows):")
    print(f'     Double-click  start_codex_ecosystem.bat')
    print()
    print("   ⚠  If you move the project folder, re-run:")
    print("       python setup_autostart.py --remove")
    print("       python setup_autostart.py")


def remove() -> None:
    removed_any = False
    for path in (VBS_PATH, VBS_PATH_LEGACY):
        if os.path.exists(path):
            os.remove(path)
            print(f"✓  Removed: {path}")
            removed_any = True
    if not removed_any:
        print("   No autostart entries found — already removed.")


def verify() -> None:
    """
    Read the installed VBS and check whether the embedded launcher path still
    exists on disk.  Prints a clear fix command when something has moved.
    """
    if not os.path.exists(VBS_PATH):
        # Check legacy path too
        if os.path.exists(VBS_PATH_LEGACY):
            print("⚠  Found old single-monitor autostart (codex_monitor.vbs).")
            print("   Upgrade it to the ecosystem launcher:")
            print("     python setup_autostart.py --remove")
            print("     python setup_autostart.py")
            sys.exit(1)
        print("✗  No autostart VBS found.")
        print("   Run:  python setup_autostart.py  to install.")
        sys.exit(1)

    content = open(VBS_PATH).read()

    # Extract all Windows-style paths from the VBS
    path_matches = re.findall(r'"([A-Za-z]:[^"]+)"', content)

    launcher_path = next((p for p in path_matches if "start_codex_ecosystem" in p.lower()), None)

    ok = True
    if launcher_path is None:
        print("✗  Could not parse launcher path from the VBS file.")
        print(f"   Inspect manually: {VBS_PATH}")
        ok = False
    elif os.path.exists(launcher_path):
        print(f"  ✓  Launcher: {launcher_path}")
    else:
        print(f"  ✗  Launcher MISSING: {launcher_path}")
        print("      Fix: python setup_autostart.py --remove && python setup_autostart.py")
        ok = False

    # Also verify the services the launcher calls
    for label, rel in [("Budget Guardian", "budget_guardian.py"),
                        ("Codex Monitor",   "monitor.py"),
                        ("Python (.venv)",  os.path.join(".venv", "Scripts", "pythonw.exe"))]:
        full = os.path.join(HERE, rel)
        if os.path.exists(full):
            print(f"  ✓  {label}: found")
        else:
            print(f"  ✗  {label}: MISSING — {full}")
            ok = False

    if ok:
        print("\n✓  All autostart paths are valid. Ecosystem will start on next login.")
    else:
        print("\n✗  Autostart is stale or incomplete — re-run setup_autostart.py to fix.")
        sys.exit(1)


if __name__ == "__main__":
    if "--remove" in sys.argv:
        remove()
    elif "--verify" in sys.argv:
        verify()
    else:
        install()
